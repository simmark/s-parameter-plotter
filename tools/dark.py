#!/usr/bin/env python3
"""Generates the dark theme: every CSS declaration with a neutral colour gets an override under html[data-theme="dark"].
Neutral colours are mirrored in lightness; saturated mid-tones (accent, curve colours) stay. Re-run after editing the stylesheet."""
import re, sys, colorsys, pathlib
path = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else 'app/index.html')
html = path.read_text(encoding='utf-8')
START, END = '/* dark:start (generated by tools/dark.py) */', '/* dark:end */'
html = re.sub(re.escape(START) + r'.*?' + re.escape(END) + r'\n?', '', html, flags=re.S)
a, b = html.index('<style>') + 7, html.index('</style>')
css = re.sub(r'/\*.*?\*/', '', html[a:b], flags=re.S)

def shift(r, g, b):
    h, l, s = colorsys.rgb_to_hls(r / 255, g / 255, b / 255)
    if s >= 0.3 and 0.25 <= l <= 0.8: return None
    nl = 0.105 + 0.82 * (1 - l)
    ns = min(s * 0.55 if nl < 0.3 else s, 0.14 if (nl < 0.3 or nl > 0.8) else 1)
    return tuple(round(255 * v) for v in colorsys.hls_to_rgb(h, nl, ns))

def convert(value):
    changed = False
    def hexrep(m):
        nonlocal changed
        h = m.group(1)
        if len(h) not in (3, 6, 8): return m.group(0)
        if len(h) == 3: h = ''.join(c * 2 for c in h)
        out = shift(int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16))
        if out is None: return m.group(0)
        changed = True
        return '#%02x%02x%02x' % out + h[6:]
    def rgbrep(m):
        nonlocal changed
        out = shift(int(m.group(2)), int(m.group(3)), int(m.group(4)))
        if out is None: return m.group(0)
        changed = True
        return '%s(%d, %d, %d' % (m.group(1), *out)
    value = re.sub(r'\bwhite\b', '#ffffff', value)
    value = re.sub(r'#([0-9a-fA-F]{3,8})\b', hexrep, value)
    value = re.sub(r'\b(rgba?)\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)', rgbrep, value)
    return value if changed else None

def split_top(text, sep):
    out, depth, cur = [], 0, ''
    for ch in text:
        if ch in '([': depth += 1
        elif ch in ')]': depth -= 1
        if ch == sep and depth == 0: out.append(cur); cur = ''
        else: cur += ch
    out.append(cur)
    return out

def walk(text):
    out, i = [], 0
    while i < len(text):
        j = text.find('{', i)
        if j < 0: break
        head = text[i:j].strip()
        depth, k = 1, j + 1
        while depth and k < len(text):
            depth += text[k] == '{'; depth -= text[k] == '}'; k += 1
        body = text[j + 1:k - 1]
        i = k
        if head.startswith('@media') or head.startswith('@supports'):
            inner = walk(body)
            if inner: out.append(head + ' {\n' + '\n'.join(inner) + '\n}')
        elif head.startswith('@'): continue
        else:
            decls = []
            for decl in split_top(body, ';'):
                if ':' not in decl: continue
                prop, value = decl.split(':', 1)
                if 'shadow' in prop: continue
                new = convert(value)
                if new: decls.append(prop.strip() + ':' + new.rstrip())
            if decls:
                sels = []
                for sel in split_top(head, ','):
                    sel = sel.strip()
                    sels.append('html[data-theme="dark"]' + ('' if sel in (':root', 'html') else ' ' + sel if not sel.startswith('html') else sel[4:]))
                out.append(', '.join(sels) + ' { ' + '; '.join(decls) + '; }')
    return out

rules = walk(css)
block = START + '\n' + '\n'.join(rules) + '\n' + END + '\n'
html = html[:b] + block + html[b:]
path.write_text(html, encoding='utf-8')
print('dark rules:', len(rules))
